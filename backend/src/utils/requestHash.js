// 幂等请求指纹（文档 §23.1）
// ===========================================================================
// 用途：同一个幂等键配不同业务参数 → 判定为客户端异常并拒绝，
//       避免「同键不同参数」被静默按首次参数执行（那会让用户在毫不知情下
//       拿到一个与他本次填写内容不符的结果）。
//
// ⚠️ **必须哈希后再落库，不能存明文拼接串**（2026-09-21 实测教训）：
//    `mini_idempotency.request_hash` 是 `varchar(64)`，业务参数一多就超长 ——
//    小程序管理端「编辑支出」直接把 `id|名称|金额|日期|类别|账户` 拼起来存，
//    请求立刻 500（`Data too long for column 'request_hash'`）。
//    钱包调增那处当时传的是 `${direction}:${amount}:${reason}`，正巧短所以没暴露，
//    但管理员一旦把「操作原因」写长到几十字，同样会 500 —— 同一个根因。
//    哈希同时还避免了把业务内容（金额/备注）长期留在幂等表里。
//
// ⚠️ **单源**：订单创建与各类管理写操作共用本函数。各写一版虽不影响正确性
//    （作用域互不相同），但长度与算法一旦分叉，排障时要读两处才知道
//    某条 hash 是怎么算出来的。故统一收口于此。
// ===========================================================================
const crypto = require('crypto');

/**
 * @param {*} payload 任意可 JSON 序列化的业务参数（对象/字符串均可）
 * @returns {string} 32 位十六进制指纹（sha256 截断，恒 ≤ 64 列宽）
 */
function hashRequest(payload) {
  return crypto.createHash('sha256').update(JSON.stringify(payload)).digest('hex').slice(0, 32);
}

module.exports = { hashRequest };
